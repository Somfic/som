//! What the generated C relies on besides the program: its prelude, the static blocks of
//! `string` literals, the shift helpers, and the compiler builtins it calls.

use crate::Emitter;
use crate::c_types::c_int;
use crate::names::identifier;
use som_mir::{BinOp, Ty, TypeId};
use std::fmt::Write;

pub(crate) const REALLOC: &str = "__builtin_realloc";
pub(crate) const FREE: &str = "__builtin_free";
pub(crate) const UNREACHABLE: &str = "__builtin_unreachable";

/// The count a `string` literal's block starts with: the largest, so it's never freed.
const STATIC_COUNT: &str = "UINTPTR_MAX";

const FNV_OFFSET: u64 = 0xcbf2_9ce4_8422_2325;
const FNV_PRIME: u64 = 0x0000_0100_0000_01b3;

const PRELUDE: &[&str] = &[
    "// Generated by the som compiler.",
    "#include <stdbool.h>",
    "#include <stdint.h>",
    "",
    "typedef uint8_t som_unit;",
    "",
    // The command-line arguments, for the standard library's `args()`.
    "static int som_argc;",
    "static char** som_argv;",
    "int32_t som_arg_count(void) { return som_argc; }",
    "uint8_t* som_arg(int32_t index) { return (uint8_t*)som_argv[index]; }",
];

impl Emitter<'_> {
    pub(crate) fn prelude(&mut self) {
        for line in PRELUDE {
            self.line(line);
        }
    }

    /// The name of the static block holding literal `text`, for a `string`: its count, its
    /// length, and its bytes with a zero byte after. Emitted once for each literal, however
    /// often it's used.
    pub(crate) fn text_block(&self, text: &str) -> String {
        // FNV-1a: a name from the bytes, so the same literal shares one block.
        let hash = (text.bytes()).fold(FNV_OFFSET, |h, b| (h ^ b as u64).wrapping_mul(FNV_PRIME));
        let name = format!("som_text_{hash:016x}");
        let block = format!(
            "static struct {{ uintptr_t count; uintptr_t len; uint8_t bytes[{}]; }} {name} = {{{STATIC_COUNT}, {}, {}}};\n",
            text.len() + 1,
            text.len(),
            c_string(text)
        );
        self.helpers
            .borrow_mut()
            .entry(name.clone())
            .or_insert(block);
        name
    }

    /// A function that shifts `x` by any `n`: `0`, or `-1` for `>>` of a negative `x`, once
    /// `n` is negative or at least the width, which C leaves undefined. Its name.
    pub(crate) fn shift_helper(&self, op: BinOp, x_ty: TypeId, n_ty: TypeId) -> String {
        let Ty::Int(int) = *self.mir.types.get(x_ty) else {
            unreachable!("checked: only integers shift")
        };
        let name = format!(
            "som_{}_{}_{}",
            if op == BinOp::ShiftLeft { "shl" } else { "shr" },
            identifier(&self.mir.display_ty(x_ty)),
            identifier(&self.mir.display_ty(n_ty))
        );
        let (c_ty, n_c_ty, unsigned) = (self.ty(x_ty), self.ty(n_ty), c_int(int).unsigned);
        let width = format!("(sizeof({c_ty}) * 8)");
        let body = match (op, int.is_signed()) {
            (BinOp::ShiftLeft, _) => {
                format!("return n < 0 || n >= {width} ? 0 : ({c_ty})(({unsigned})x << n);")
            }
            (_, true) => format!("return n < 0 || n >= {width} ? (x < 0 ? -1 : 0) : x >> n;"),
            (_, false) => format!("return n < 0 || n >= {width} ? 0 : x >> n;"),
        };
        self.helpers
            .borrow_mut()
            .entry(name.clone())
            .or_insert_with(|| {
                format!("static {c_ty} {name}({c_ty} x, {n_c_ty} n) {{ {body} }}\n")
            });
        name
    }
}

/// A C string literal with the same bytes as `s`.
pub(crate) fn c_string(s: &str) -> String {
    let mut out = String::from("\"");
    for byte in s.bytes() {
        match byte {
            b'"' | b'\\' => write!(out, "\\{}", byte as char).unwrap(),
            0x20..=0x7e => out.push(byte as char),
            // Octal escapes are at most three digits, so a following digit can't extend them.
            _ => write!(out, "\\{byte:03o}").unwrap(),
        }
    }
    out.push('"');
    out
}
